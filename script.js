// Property filter tabs (event delegation so it keeps working after re-render)
let currentFilter = "all";
function applyActiveFilter() {
  document.querySelectorAll("#propertyGrid .property-card").forEach(card => {
    const show = currentFilter === "all" || card.getAttribute("data-type") === currentFilter;
    card.style.display = show ? "" : "none";
  });
}
document.querySelectorAll(".tab").forEach(tab => {
  tab.addEventListener("click", () => {
    document.querySelectorAll(".tab").forEach(t => t.classList.remove("active"));
    tab.classList.add("active");
    currentFilter = tab.getAttribute("data-filter");
    applyActiveFilter();
  });
});

