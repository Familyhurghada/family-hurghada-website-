// These render from the JSON files in /data — edit those files (directly or
// via the /admin panel) to add, change or remove listings without touching this code.
let propertiesData = [];
let projectsData = [];
let testimonialsData = [];

async function loadJSON(path) {
  try {
    const res = await fetch(path, { cache: "no-store" });
    if (!res.ok) return {};
    return await res.json();
  } catch (e) {
    console.warn("Could not load " + path + " (this is expected if you're opening index.html directly instead of via a web server).", e);
    return {};
  }
}

const homeIconSvg = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.2"><path d="M3 11l9-7 9 7"/><path d="M5 10v10h14V10"/><path d="M9 20v-6h6v6"/></svg>';

function propertyCardHTML(item, lang) {
  const title = (item.title && item.title[lang]) || (item.title && item.title.en) || "";
  const details = (item.details && item.details[lang]) || (item.details && item.details.en) || "";
  const tag = translations[lang]["properties.filter." + item.type] || item.type;
  const sampleLabel = translations[lang]["properties.sample"] || "Sample";
  const media = item.image
    ? `<img src="${item.image}" alt="${title}" style="width:100%;height:100%;object-fit:cover;">`
    : homeIconSvg + `<span class="sample-badge">${sampleLabel}</span>`;
  return `
    <div class="property-card" data-type="${item.type}">
      <div class="prop-media">${media}</div>
      <div class="prop-body">
        <div class="prop-tag">${tag}</div>
        <h3>${title}</h3>
        <p>${details}</p>
      </div>
    </div>`;
}

function projectCardHTML(item, lang) {
  const title = (item.title && item.title[lang]) || (item.title && item.title.en) || "";
  const details = (item.details && item.details[lang]) || (item.details && item.details.en) || "";
  const area = (item.area && item.area[lang]) || (item.area && item.area.en) || "";
  const badgeLabel = translations[lang]["projects.badge"] || "Coming Soon";
  const media = item.image
    ? `<img src="${item.image}" alt="${title}" style="width:100%;height:100%;object-fit:cover;">`
    : homeIconSvg + `<span class="sample-badge badge-projects">${badgeLabel}</span>`;
  return `
    <div class="property-card project-card">
      <div class="prop-media">${media}</div>
      <div class="prop-body">
        <div class="prop-tag">${area}</div>
        <h3>${title}</h3>
        <p>${details}</p>
      </div>
    </div>`;
}

function testimonialCardHTML(item, lang) {
  const quote = (item.quote && item.quote[lang]) || (item.quote && item.quote.en) || "";
  const detail = (item.detail && item.detail[lang]) || (item.detail && item.detail.en) || "";
  return `
    <div class="testimonial-card">
      <div class="t-quote-mark">&ldquo;</div>
      <p class="t-quote">${quote}</p>
      <div class="t-name">${item.name || ""}</div>
      <div class="t-detail">${detail}</div>
    </div>`;
}

function renderDynamicContent(lang) {
  const propGrid = document.getElementById("propertyGrid");
  if (propGrid) {
    propGrid.innerHTML = propertiesData.map(item => propertyCardHTML(item, lang)).join("");
  }
  const projGrid = document.getElementById("projectGrid");
  if (projGrid) {
    projGrid.innerHTML = projectsData.map(item => projectCardHTML(item, lang)).join("");
  }
  const tGrid = document.getElementById("testimonialGrid");
  if (tGrid) {
    tGrid.innerHTML = testimonialsData.map(item => testimonialCardHTML(item, lang)).join("");
  }
  applyActiveFilter();
}

async function initDynamicContent() {
  const [propRes, projRes, testRes] = await Promise.all([
    loadJSON("data/properties.json"),
    loadJSON("data/projects.json"),
    loadJSON("data/testimonials.json")
  ]);
  propertiesData = propRes.items || [];
  projectsData = projRes.items || [];
  testimonialsData = testRes.items || [];
  renderDynamicContent(currentLang);
}

